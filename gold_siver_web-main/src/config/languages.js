export const getLanguageByCode = (inputCode) => {
  const normalized = (inputCode || "").toLowerCase();
  if (!normalized) return null;

  const exactMatch = SUPPORTED_LANGUAGES.find(
    (language) => language.code.toLowerCase() === normalized,
  );
  if (exactMatch) return exactMatch;

  const baseCode = normalized.split("-")[0];
  return (
    SUPPORTED_LANGUAGES.find(
      (language) => language.code.toLowerCase().split("-")[0] === baseCode,
    ) || null
  );
};

export const getLanguageFlagByCode = (inputCode) =>
  getLanguageByCode(inputCode)?.flag || "🌐";

const getCountryCodeFromFlagEmoji = (flagEmoji = "") => {
  const symbols = Array.from(flagEmoji);
  if (symbols.length !== 2) return null;

  const regionalIndicatorA = 0x1f1e6;
  const regionalIndicatorZ = 0x1f1ff;
  let countryCode = "";

  for (const symbol of symbols) {
    const codePoint = symbol.codePointAt(0);
    if (codePoint < regionalIndicatorA || codePoint > regionalIndicatorZ) {
      return null;
    }
    countryCode += String.fromCharCode(codePoint - regionalIndicatorA + 65);
  }

  return countryCode.toLowerCase();
};

export const getLanguageFlagMeta = (language) => {
  if (!language) {
    return { type: "emoji", value: "🌐", alt: "Language" };
  }

  const countryCode = getCountryCodeFromFlagEmoji(language.flag);
  if (countryCode) {
    return {
      type: "image",
      value: `https://flagcdn.com/24x18/${countryCode}.png`,
      alt: `${language.name} flag`,
    };
  }

  return {
    type: "emoji",
    value: language.flag || "🌐",
    alt: `${language.name} flag`,
  };
};

export const getLanguageFlagMetaByCode = (inputCode) =>
  getLanguageFlagMeta(getLanguageByCode(inputCode));
