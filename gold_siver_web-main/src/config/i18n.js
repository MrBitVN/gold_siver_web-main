const supportedLanguageCodes = new Set(
  SUPPORTED_LANGUAGES.map((language) => language.code.toLowerCase()),
);

const normalizeLanguageCode = (lang = "") => {
  if (!lang) return "vi";
  const exactCode = lang.toLowerCase();
  if (supportedLanguageCodes.has(exactCode)) {
    return SUPPORTED_LANGUAGES.find(
      (language) => language.code.toLowerCase() === exactCode,
    )?.code;
  }

  const baseCode = exactCode.split("-")[0];
  if (supportedLanguageCodes.has(baseCode)) {
    return SUPPORTED_LANGUAGES.find(
      (language) => language.code.toLowerCase() === baseCode,
    )?.code;
  }

  return "vi";
};

const getInitialLanguage = () => {
  // Ưu tiên 1: localStorage (chỉ client)
  if (typeof window !== "undefined") {
    try {
      const savedLang = localStorage.getItem("lang");
      if (savedLang) return normalizeLanguageCode(savedLang);
    } catch (error) {
      console.warn("localStorage unavailable in getInitialLanguage:", error);
    }
  }

  // Ưu tiên 2: Ngôn ngữ trình duyệt
  if (typeof navigator !== "undefined") {
    return normalizeLanguageCode(navigator.language);
  }

  // Mặc định
  return "vi";
};

const defaultLang = getInitialLanguage();

if (typeof window !== "undefined") {
  try {
    const cachedResource = localStorage.getItem(
      `i18n_resource_${TRANSLATION_CACHE_VERSION}_${defaultLang}`,
    );
    if (cachedResource && defaultLang !== "vi" && !resources[defaultLang]) {
      try {
        resources[defaultLang] = {
          translation: JSON.parse(cachedResource),
        };
      } catch (error) {
        console.warn("Failed to parse cached i18n resource:", error);
      }
    }
  } catch (error) {
    console.warn("localStorage unavailable while loading cached resources:", error);
  }
}

